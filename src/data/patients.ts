export type PatientStatus = "stable" | "observation" | "critical" | "outpatient" | "discharged";

export interface Patient {
  id: string;
  name: string;
  age: number;
  sex: "F" | "M";
  /** Medical record number shown on charts and in chat mentions. */
  mrn: string;
  avatar?: string;
  department: string;
  doctorId: string;
  status: PatientStatus;
  /** Ward and bed for admitted patients. */
  ward?: string;
  bed?: string;
  admittedAt?: string;
  condition: string;
  allergies: string[];
  insurerId?: string;
  bloodType: string;
  phone: string;
  /** Latest vitals: heart rate, blood pressure, SpO2, temperature, respiration rate. */
  vitals: { hr: number; bp: string; spo2: number; temp: number; rr: number };
  /** National Early Warning Score, 0–20. 5+ needs urgent review. */
  news: number;
}

