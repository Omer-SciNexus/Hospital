export const productsById = Object.fromEntries(products.map((p) => [p.id, p])) as Record<string, Product>;

export function getProduct(id: string) {
  return productsById[id];
}

export function productsForDepartment(slug: string) {
  return products.filter((p) => p.departments.includes(slug));
}

export function relatedProducts(product: Product, limit = 4) {
  return products
    .filter((p) => p.id !== product.id && (p.category === product.category || p.departments.some((d) => product.departments.includes(d))))
    .sort((a, b) => Number(b.category === product.category) - Number(a.category === product.category) || b.rating - a.rating)
    .slice(0, limit);
}

